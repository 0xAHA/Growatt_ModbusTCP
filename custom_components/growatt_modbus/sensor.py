async def async_setup_entry(
    hass: HomeAssistant,
    config_entry: ConfigEntry,
    async_add_entities: AddEntitiesCallback,
) -> None:
    """Set up Growatt Modbus sensors."""
    coordinator = config_entry.runtime_data
    
    # Wait for first data to determine which sensors to create
    if coordinator.data is None:
        _LOGGER.warning("No data available from coordinator during sensor setup")
        return
    
    # Get the inverter series profile
    inverter_series = config_entry.data.get(CONF_INVERTER_SERIES, "min_7000_10000_tl_x")
    available_sensors = get_sensors_for_profile(inverter_series)
    
    _LOGGER.info(
        "Setting up sensors for %s - %d sensors available in profile",
        inverter_series,
        len(available_sensors)
    )
    
    entities = []
    
    # Create sensors based on available data and conditions
    for sensor_key, sensor_def in SENSOR_DEFINITIONS.items():
        # Check if sensor is supported by this inverter profile
        if sensor_key not in available_sensors:
            _LOGGER.debug("Skipping sensor %s - not in profile %s", sensor_key, inverter_series)
            continue
        
        # Check if sensor should be created based on condition
        if "condition" in sensor_def:
            try:
                if not sensor_def["condition"](coordinator.data):
                    _LOGGER.debug("Skipping sensor %s - condition not met", sensor_key)
                    continue
            except (AttributeError, TypeError) as e:
                _LOGGER.debug("Skipping sensor %s - error checking condition: %s", sensor_key, e)
                continue
        
        entities.append(
            GrowattModbusSensor(
                coordinator,
                config_entry,
                sensor_key,
                sensor_def,
            )
        )
    
    # Not register-driven, so it is not in SENSOR_DEFINITIONS: it reads the RTC directly
    # rather than coming out of a GrowattData field. Off-grid profiles encode the year
    # differently and are excluded, same as the sync button (#393).
    if coordinator.modbus_client.is_clock_supported:
        entities.append(GrowattInverterClockSensor(coordinator, config_entry))

    _LOGGER.info("Created %d sensors for %s", len(entities), inverter_series)
    async_add_entities(entities)

    # Deferred entity registration (Issue #262)
    # async_config_entry_first_refresh always seeds coordinator.data with an empty
    # GrowattData() placeholder — no inverter read occurs at setup time. Sensors
    # whose creation is gated on a condition (e.g. hasattr(data, 'battery_soh'))
    # therefore fail the check and are silently skipped, even when the inverter is
    # online. This affects every startup, not just ones where the inverter is offline.
    #
    # Fix: collect every in-profile, condition-gated sensor that wasn't created, then
    # register a coordinator listener that re-evaluates those conditions once real data
    # arrives (coordinator.has_real_data becomes True). Any that now pass are added via
    # async_add_entities. The listener removes itself when all deferred sensors are
    # resolved or the config entry is unloaded.
    # Only the register-driven sensors carry a _sensor_key. GrowattInverterClockSensor
    # does not, and it is in this same list - iterating all of them raised AttributeError
    # in v1.8.6-v1.8.8, which aborted setup right here, after the unconditioned sensors
    # had been added and before the deferred block below ever ran. Every condition-gated
    # sensor silently ceased to exist, with no repair and no automation warning (#399).
    created_keys = {
        e._sensor_key for e in entities if isinstance(e, GrowattModbusSensor)
    }
    deferred: list[tuple[str, dict]] = [
        (sk, sd)
        for sk, sd in SENSOR_DEFINITIONS.items()
        if sk in available_sensors and "condition" in sd and sk not in created_keys
    ]

    if deferred:
        _LOGGER.debug(
            "%d sensor(s) deferred pending first real inverter data: %s",
            len(deferred),
            [sk for sk, _ in deferred],
        )

        @callback
        def _async_check_deferred_sensors() -> None:
            if not coordinator.has_real_data:
                return
            new_entities = []
            still_waiting: list[tuple[str, dict]] = []
            for sensor_key, sensor_def in deferred:
                try:
                    if sensor_def["condition"](coordinator.data):
                        new_entities.append(
                            GrowattModbusSensor(coordinator, config_entry, sensor_key, sensor_def)
                        )
                        _LOGGER.debug("Deferred sensor %s condition met — adding entity", sensor_key)
                    else:
                        still_waiting.append((sensor_key, sensor_def))
                except Exception as exc:  # noqa: BLE001
                    _LOGGER.debug("Deferred sensor %s condition error (%s) — dropping", sensor_key, exc)
            deferred.clear()
            deferred.extend(still_waiting)
            if new_entities:
                async_add_entities(new_entities)
            if not deferred:
                _remove_listener()

        _remove_listener = coordinator.async_add_listener(_async_check_deferred_sensors)
        config_entry.async_on_unload(_remove_listener)


class GrowattInverterClockSensor(GrowattEntity, SensorEntity):
    """The inverter's own real-time clock.

    Worth exposing because time-of-use windows fire against *this* clock, not Home
    Assistant's: a window set for 13:00 starts whenever the inverter believes it is 13:00.
    A reporter's export window was running two minutes late for exactly that reason, and
    there was no way to see it without a manual register read.

    Disabled by default and diagnostic, which puts it next to the Inverter Clock Sync
    button. Enabling it costs one extra holding-register read per poll - the coordinator
    does not read the RTC at all until this sensor asks it to.
    """

    # Deliberately NOT SensorDeviceClass.TIMESTAMP. Home Assistant renders a timestamp
    # sensor as relative time - "12 seconds ago", ticking every second - which is useless
    # for reading a clock and looks like a broken "last updated" field. The point of this
    # entity is to show what time the inverter thinks it is, so the state is the formatted
    # wall-clock time and the machine-readable form is an attribute.
    _attr_entity_category = EntityCategory.DIAGNOSTIC
    _attr_entity_registry_enabled_default = False
    _attr_icon = "mdi:clock-outline"
    _attr_translation_key = "inverter_clock"

    def __init__(self, coordinator, config_entry: ConfigEntry) -> None:
        """Initialise the inverter clock sensor."""
        super().__init__(
            coordinator,
            config_entry,
            unique_key="inverter_clock",
            device_type=get_device_type_for_sensor("inverter_clock"),
        )

    async def async_added_to_hass(self) -> None:
        """Ask the coordinator to start reading the RTC.

        Disabled entities are never added, so a user who leaves this off never pays for
        the extra read.
        """
        await super().async_added_to_hass()
        self.coordinator.enable_clock_polling()

    @property
    def available(self) -> bool:
        """Unavailable until the clock has actually been read.

        The first poll after enabling has usually not happened yet, and on a model whose
        RTC registers do not decode it never will - better unavailable than a made-up
        timestamp.
        """
        return (
            self.coordinator.last_update_success
            and self.coordinator.is_online
            and self.coordinator.inverter_clock is not None
        )

    @property
    def native_value(self) -> str | None:
        """Return the inverter's clock as readable local wall-clock time."""
        value = self.coordinator.inverter_clock
        if value is None:
            return None
        return value.strftime("%Y-%m-%d %H:%M:%S")

    @property
    def extra_state_attributes(self) -> dict[str, Any]:
        """Drift, plus the timestamp in a form templates and automations can parse.

        Positive drift means the inverter is ahead of Home Assistant. The registers hold
        wall-clock time with no timezone, so the local zone is attached for `timestamp`.
        """
        value = self.coordinator.inverter_clock
        if value is None:
            return {}
        drift = (value - dt_util.now().replace(tzinfo=None)).total_seconds()
        return {
            "timestamp": value.replace(tzinfo=dt_util.DEFAULT_TIME_ZONE).isoformat(),
            "drift_seconds": round(drift),
            "drift_minutes": round(drift / 60, 1),
        }


def _signed_grid_power(data) -> float | None:
    """Grid power as one signed number, positive = export. None when it is not knowable.

    Grid Power, Grid Export Power and Grid Import Power are three views of one quantity,
    and each used to derive it with its own byte-identical copy of this logic. Two defects
    lived in all three copies at once (#228):

    **A negative reading was ignored.** `meter_power` is a single signed register; the MID
    V2.01 profile negates it on combine so that an importing site arrives here as a
    *negative* `power_to_grid`. Nothing tested for that - `export > 0` failed, `import_power
    > 0` failed, and the deliberately-produced signed meter reading was discarded in favour
    of the estimate below, precisely when it said "importing".

    **The estimate ran with nothing to estimate from.** With no smart meter the directional
    registers read 0, and on a grid-tied profile `charge_power` and `discharge_power` are
    not mapped at all. `(solar + 0) - (0 + 0)` is just `solar`, so a reporter importing
    240 W was shown 74 W of export - which was his PV output wearing a grid label. The
    MID profile already documents that these registers read 0 without a meter and says to
    use the AC power entities instead; the sensor was overriding that with a fabrication.

    Returning None makes the entity unknown, which is the honest answer: without a meter
    we do not know the grid flow.
    """
    export = getattr(data, "power_to_grid", 0) or 0
    import_power = getattr(data, "power_to_user", 0) or 0

    # A directional register carrying a real reading always wins.
    if export > 0:
        return float(export)
    if import_power > 0:
        return float(-import_power)
    if export < 0:
        # Signed meter reading indicating import. See above.
        return float(export)

    solar = getattr(data, "pv_total_power", 0) or 0
    load = getattr(data, "power_to_load", 0) or 0
    charge = getattr(data, "charge_power", 0) or 0
    discharge = getattr(data, "discharge_power", 0) or 0

    if load == 0 and charge == 0 and discharge == 0:
        # Nothing to balance solar against. With no generation either, the site really is
        # idle and zero is a fair answer; with generation, the expression degenerates to
        # `solar` and would be published as grid flow.
        return 0.0 if solar == 0 else None

    return float((solar + discharge) - (load + charge))


class GrowattModbusSensor(GrowattEntity, SensorEntity):
    """Representation of a Growatt Modbus sensor."""

    def __init__(
        self,
        coordinator: GrowattModbusCoordinator,
        config_entry: ConfigEntry,
        sensor_key: str,
        sensor_def: dict[str, Any],
    ) -> None:
        """Initialize the sensor."""
        # unique_key is the sensor key, preserving the existing unique ID exactly.
        super().__init__(
            coordinator,
            config_entry,
            sensor_key,
            get_device_type_for_sensor(sensor_key),
        )

        self._sensor_key = sensor_key
        self._sensor_def = sensor_def

        # Name comes from strings.json / translations/*.json under entity.sensor.<key>.name
        # rather than from sensor_def['name'], so the 22 shipped languages can translate it.
        # The English text there was generated from sensor_def['name'], so what users see is
        # unchanged; tests_ha asserts every key has an entry, because a missing one leaves
        # the entity with no name at all rather than falling back.
        self._attr_translation_key = sensor_key

        # Set entity category (None for main sensors, "diagnostic" for technical details)
        entity_category = get_entity_category(sensor_key)
        if entity_category == "diagnostic":
            self._attr_entity_category = EntityCategory.DIAGNOSTIC

        # Set sensor attributes based on definition
        if "device_class" in sensor_def:
            self._attr_device_class = sensor_def["device_class"]
        if "state_class" in sensor_def:
            self._attr_state_class = sensor_def["state_class"]
        if "unit" in sensor_def:
            self._attr_native_unit_of_measurement = sensor_def["unit"]
        if "icon" in sensor_def:
            self._attr_icon = sensor_def["icon"]
        if sensor_def.get("disabled_by_default"):
            self._attr_entity_registry_enabled_default = False

    @property
    def available(self) -> bool:
        """Entity is available only when coordinator succeeded AND inverter is online.

        When the inverter stops responding to Modbus (truly offline), all entities
        go unavailable. HA's statistics engine ignores unavailable states, preventing
        flatline data from being recorded as real measurements. When the inverter is
        online but dormant (responds with zeros), available stays True and the
        coordinator's retention logic protects total_increasing sensors.
        """
        return self.coordinator.last_update_success and self.coordinator.is_online

    @property
    def native_value(self) -> Any:
        """Return the state of the sensor."""
        if self.coordinator.data is None:
            return None
        
        data = self.coordinator.data
        
        # Get invert grid power option
        invert_grid_power = self._config_entry.options.get(CONF_INVERT_GRID_POWER, False)
        inverter_series = self._config_entry.data.get(CONF_INVERTER_SERIES, "").lower()
        is_sph_family = inverter_series.startswith("sph_")
        # XH hybrid models (MOD-XH, etc.) expose energy_to_user registers via 3000-range
        is_xh_hybrid = "xh" in inverter_series
        
        # Special handling for calculated sensors
        if self._sensor_def.get("attr") == "calculated":
            if self._sensor_key == "grid_power":
                # Bidirectional grid power (signed value)
                # Positive = export, Negative = import
                # Per VPP V2.03: power_to_grid = "Total reverse power (grid export)"
                # Per VPP V2.03: power_to_user = "Total forward power (grid import)"
                grid_power = _signed_grid_power(data)
                if grid_power is None:
                    return None

                # Apply inversion if configured (CT clamp backwards)
                if invert_grid_power:
                    grid_power = -grid_power

                raw_value = round(grid_power, 1)

                # Apply offline behavior
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

            elif self._sensor_key == "grid_export_power":
                # Export power (always positive or 0)
                # Per VPP V2.03: power_to_grid = "Total reverse power (grid export)"
                # Per VPP V2.03: power_to_user = "Total forward power (grid import)"
                # invert_grid_power is a sign-convention correction for the signed
                # grid_power sensor only — do NOT apply it here. The always-positive
                # sensors derive from the directional values directly.
                grid_power = _signed_grid_power(data)
                if grid_power is None:
                    return None

                # Export = positive portion of raw signed value
                raw_value = round(max(0, grid_power), 1)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

            elif self._sensor_key == "grid_import_power":
                # Import power (always positive or 0)
                # Per VPP V2.03: power_to_user = "Total forward power (grid import)"
                # Per VPP V2.03: power_to_grid = "Total reverse power (grid export)"
                # Same derivation — no inversion applied (see grid_export_power comment).
                grid_power = _signed_grid_power(data)
                if grid_power is None:
                    return None

                # Import = negative portion of raw signed value, flipped to positive
                raw_value = round(max(0, -grid_power), 1)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
                
            elif self._sensor_key == "self_consumption":
                # Self consumption = solar used directly
                solar = getattr(data, "pv_total_power", 0)
                export = getattr(data, "power_to_grid", 0)
                load = getattr(data, "power_to_load", 0)
                
                if export > 0:
                    self_consumption = solar - export
                elif load > 0:
                    self_consumption = min(solar, load)
                else:
                    self_consumption = solar
                
                raw_value = round(max(0, self_consumption), 1)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
            
            elif self._sensor_key == "self_consumption_percentage":
                # Percentage of solar self-consumed
                solar = getattr(data, "pv_total_power", 0)
                export = getattr(data, "power_to_grid", 0)
                load = getattr(data, "power_to_load", 0)
                
                if solar == 0:
                    raw_value = 0
                else:
                    if export > 0:
                        self_consumption = solar - export
                    elif load > 0:
                        self_consumption = min(solar, load)
                    else:
                        self_consumption = solar
                    
                    percentage = (max(0, self_consumption) / solar) * 100
                    raw_value = round(percentage, 1)
                
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
                
            elif self._sensor_key == "house_consumption":
                # House consumption
                load = getattr(data, "power_to_load", 0)

                if load == 0:
                    # Energy balance: solar + battery_discharge - battery_charge + grid_import - grid_export
                    # self_consumption_power (reg 1037/1038 on HU) is NOT used — it reports
                    # solar self-consumed, not total house load (omits battery discharge + grid import).
                    solar = getattr(data, "pv_total_power", 0)
                    export = getattr(data, "power_to_grid", 0)
                    import_power = getattr(data, "power_to_user", 0)
                    charge = getattr(data, "charge_power", 0)
                    discharge = getattr(data, "discharge_power", 0)
                    has_battery = (charge > 0 or discharge > 0)
                    has_grid = (export > 0 or import_power > 0)
                    if has_battery or has_grid:
                        load = solar + discharge - charge + import_power - export
                    else:
                        load = max(0, solar - export)

                raw_value = round(max(0, load), 1)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
            
            elif self._sensor_key == "battery_power":
                # Battery power: positive = charging, negative = discharging
                charge_power = getattr(data, "charge_power", 0)
                discharge_power = getattr(data, "discharge_power", 0)
                
                if charge_power > 0:
                    raw_value = round(charge_power, 1)  # Positive for charging
                elif discharge_power > 0:
                    raw_value = round(-discharge_power, 1)  # Negative for discharging
                else:
                    raw_value = 0
                
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
            
            
            elif self._sensor_key == "grid_energy_today":
                # Net grid energy = export − import. Positive = net export for the day.
                export_energy = getattr(data, "energy_to_grid_today", 0)

                # SPH / XH hybrids: use the hardware bidirectional meter directly.
                # The formula (load + export − energy_today) is wrong on these models
                # because energy_today is MPPT DC yield, not AC output. Issue #336.
                if is_sph_family or is_xh_hybrid:
                    import_energy = getattr(data, "energy_to_user_today", 0)
                else:
                    load_energy = getattr(data, "load_energy_today", 0)
                    solar_energy = getattr(data, "energy_today", 0)
                    import_energy = max(0, load_energy - solar_energy + export_energy)

                net_energy = export_energy - import_energy

                if invert_grid_power:
                    net_energy = -net_energy

                raw_value = round(net_energy, 2)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

            elif self._sensor_key == "grid_energy_total":
                # Net grid energy = export − import. Positive = net export lifetime.
                export_energy = getattr(data, "energy_to_grid_total", 0)

                # SPH / XH hybrids: use the hardware bidirectional meter directly.
                # The formula is unreliable on hybrid models because energy_total
                # includes battery cycling losses. Issue #336.
                if is_sph_family or is_xh_hybrid:
                    import_energy = getattr(data, "energy_to_user_total", 0)
                else:
                    load_energy = getattr(data, "load_energy_total", 0)
                    solar_energy = getattr(data, "energy_total", 0)
                    import_energy = max(0, load_energy - solar_energy + export_energy)

                net_energy = export_energy - import_energy

                if invert_grid_power:
                    net_energy = -net_energy

                raw_value = round(net_energy, 2)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

            elif self._sensor_key == "grid_import_energy_today":
                # Grid import energy - use hardware register if available, otherwise calculate.
                # SPH: energy_to_user_today (hardware bidirectional meter = grid import)
                # MOD-XH and other XH hybrids: same register via 3000-range (3067/3068) — Issue #336
                # Other models: energy_from_grid_today or calculation
                #
                # The calculation (load + export - energy_today) is WRONG for XH hybrids because
                # energy_today on those models is PV DC energy (use_mppt_energy_today=True), not
                # AC inverter output. The hardware register gives the correct value directly.
                energy_to_user_today = getattr(data, "energy_to_user_today", 0)
                has_hardware_import = (
                    hasattr(data, "energy_from_grid_today") or
                    (is_sph_family or is_xh_hybrid) or
                    "wit_" in inverter_series
                )

                if has_hardware_import:
                    # Hardware bidirectional meter — do NOT gate on > 0.
                    # A zero reading is valid (no grid import yet today); gating on > 0
                    # caused the broken formula path to fire on hybrid profiles mid-day,
                    # producing values that rise then fall as PV output increases. Issue #336.
                    # energy_from_grid_today takes priority if present; fall back to energy_to_user_today.
                    raw_value = getattr(data, "energy_from_grid_today", energy_to_user_today)
                else:
                    # No hardware import register — calculate from load/solar/export.
                    # Valid for non-hybrid inverters (MIN, etc.) where energy_today = AC output.
                    load_energy = getattr(data, "load_energy_today", 0)
                    solar_energy = getattr(data, "energy_today", 0)
                    export_energy = getattr(data, "energy_to_grid_today", 0)
                    raw_value = max(0, load_energy - solar_energy + export_energy)

                raw_value = round(raw_value, 2)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

            elif self._sensor_key == "grid_import_energy_total":
                # Grid import energy total - same hardware-first logic as the daily sensor.
                # SPH: energy_to_user_total from hardware register
                # MOD-XH and other XH hybrids: same register via 3000-range (3069/3070) — Issue #336
                # The lifetime calculation (load_total + export_total - energy_total) is unreliable
                # for hybrid models because energy_total includes battery cycling losses.
                energy_to_user_total = getattr(data, "energy_to_user_total", 0)
                has_hardware_import = (
                    hasattr(data, "energy_from_grid_total") or
                    (is_sph_family or is_xh_hybrid) or
                    "wit_" in inverter_series
                )

                if has_hardware_import:
                    # Hardware bidirectional meter — do NOT gate on > 0 (same fix as daily sensor).
                    # energy_from_grid_total takes priority if present; fall back to energy_to_user_total.
                    raw_value = getattr(data, "energy_from_grid_total", energy_to_user_total)
                else:
                    # No hardware import register — calculate from load/solar/export.
                    # Valid for non-hybrid inverters (MIN, etc.).
                    load_energy = getattr(data, "load_energy_total", 0)
                    solar_energy = getattr(data, "energy_total", 0)
                    export_energy = getattr(data, "energy_to_grid_total", 0)
                    raw_value = max(0, load_energy - solar_energy + export_energy)

                raw_value = round(raw_value, 2)
                return self.coordinator.get_sensor_value(self._sensor_key, raw_value)
            
            elif self._sensor_key == "last_update":
                # Get the last successful update time from coordinator
                if hasattr(self.coordinator, 'last_update_success_time') and self.coordinator.last_update_success_time:
                    # Make sure datetime is timezone-aware (UTC)
                    dt = self.coordinator.last_update_success_time
                    if dt.tzinfo is None:
                        # If naive datetime, assume UTC and make it aware
                        dt = dt.replace(tzinfo=timezone.utc)
                    return dt
                return None

            elif self._sensor_key == "grid_connection_status":
                if not self.coordinator.is_online:
                    return "Offline"
                # Use VPP equipment_status (reg 31000) when available in the active profile.
                # equipment_status_valid distinguishes "register present but reads 0 (Standby)"
                # from "register not in this profile" — both yield equipment_status=0 otherwise.
                if data.equipment_status_valid:
                    # V2.01 equipment_status (reg 31000): 5/6=On-grid, 7/8=Off-grid/EPS
                    status = data.equipment_status
                    if status in (5, 6):
                        return "On-grid"
                    if status in (7, 8):
                        return "Off-grid"
                    return "Unknown"
                else:
                    # Legacy inverter_status (reg 0): 0=Waiting, 1=Normal, 3=Fault
                    # For all grid-tied/hybrid profiles 0 (idle) and 1 (normal) both
                    # indicate a grid connection — distinguish from off-grid is not possible
                    # without equipment_status.
                    status = data.status
                    if status in (0, 1):
                        return "On-grid"
                    return "Unknown"

            return None

        # MIN TL-XH energy_today register (3049/3050) can represent total system AC
        # output and include battery discharge. For solar reporting, derive PV-only
        # daily energy from energy balance terms.
        if self._sensor_key == "energy_today" and inverter_series.startswith("min_tl_xh_"):
            load_energy = getattr(data, "load_energy_today", 0.0)
            grid_import = getattr(data, "energy_to_user_today", 0.0)
            grid_export = getattr(data, "energy_to_grid_today", 0.0)
            battery_charge = getattr(data, "charge_energy_today", 0.0)
            battery_discharge = getattr(data, "discharge_energy_today", 0.0)

            pv_energy_today = load_energy + battery_charge + grid_export - grid_import - battery_discharge
            pv_energy_today = round(max(0.0, pv_energy_today), 2)

            return self.coordinator.get_sensor_value(self._sensor_key, pv_energy_today)
        
        # Regular sensor - get value from data attribute
        attr = self._sensor_def["attr"]

        # Report nothing when the register behind this sensor was not read this poll (#384).
        #
        # A failed block read used to publish 0, which is indistinguishable from a real zero
        # and lands in long-term statistics as a measurement. A reporter's solar graph showed
        # a vertical drop to 0 W and back within one poll, with no error anywhere, because
        # from Home Assistant's side the poll had succeeded.
        #
        # Returning None makes the entity unknown for that poll, so history shows a gap. A
        # gap is honest about what happened; a zero is a claim the inverter never made.
        if attr in getattr(data, "unread_fields", ()):
            return None

        value = getattr(data, attr, None)
        
        if value is None:
            return None
        
        # Special handling for status sensor
        if self._sensor_key == "status":
            from .const import STATUS_CODES, HYBRID_STATUS_CODES, SPF_STATUS_CODES, PROFILE_STATUS_MAP

            if not self.coordinator.is_online:
                return "Offline"

            client = self.coordinator.modbus_client
            map_key = PROFILE_STATUS_MAP.get(client.register_map_name if client else '', 'grid_tied')
            codes = HYBRID_STATUS_CODES if map_key == 'hybrid' else (SPF_STATUS_CODES if map_key == 'spf' else STATUS_CODES)
            return codes.get(int(value), {"name": f"Unknown ({value})"})["name"]

        # Special handling for derating_mode sensor
        if self._sensor_key == "derating_mode":
            from .const import get_derating_name
            return get_derating_name(int(value))

        # Apply value map if defined (returns named string instead of raw integer)
        if "value_map" in self._sensor_def:
            return self._sensor_def["value_map"].get(int(value), f"Unknown ({value})")

        # Round numeric values to reasonable precision
        if isinstance(value, float):
            if self._sensor_def.get("unit") == UnitOfPower.WATT:
                raw_value = round(value, 1)
            elif self._sensor_def.get("unit") == UnitOfElectricPotential.VOLT:
                raw_value = round(value, 1)
            elif self._sensor_def.get("unit") == UnitOfElectricCurrent.AMPERE:
                raw_value = round(value, 2)
            elif self._sensor_def.get("unit") == UnitOfFrequency.HERTZ:
                raw_value = round(value, 2)
            elif self._sensor_def.get("unit") == UnitOfTemperature.CELSIUS:
                raw_value = round(value, 1)
            elif self._sensor_def.get("unit") == UnitOfEnergy.KILO_WATT_HOUR:
                raw_value = round(value, 2)
            else:
                raw_value = value
        else:
            raw_value = value
        
        # Apply offline behavior for this sensor
        return self.coordinator.get_sensor_value(self._sensor_key, raw_value)

    @property
    def extra_state_attributes(self) -> dict[str, Any] | None:
        """Return additional state attributes."""
        desc = self._sensor_def.get("description")
        if desc:
            return {"description": desc}
        return None
